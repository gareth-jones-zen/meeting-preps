"""Writes src/MeetingPreps/PromptText.g.cs from the Python's prompts.py, so the templates are the same text byte for
byte. Run from the repo root: python -I tools/gen/prompts_to_cs.py <path to prompts.py>"""
import importlib.util
import pathlib
import sys

spec = importlib.util.spec_from_file_location("prompts", sys.argv[1])
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


def literal(text: str) -> str:
    out = []
    for c in text:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif 0x20 <= ord(c) < 0x7f:
            out.append(c)
        else:
            out.append("\\u" + f"{ord(c):04x}")
    return '"' + "".join(out) + '"'


lines = ["// Generated by tools/gen/prompts_to_cs.py from the Python's prompts.py. Don't edit: regenerate.",
         "namespace MeetingPreps;", "", "internal static class PromptText", "{"]
for name in ("PREP", "COMPANION", "UPDATE", "REFRESH"):
    lines.append(f"    public const string {name.title()} =")
    text = getattr(module, name)
    chunks = text.split("\n")
    for i, chunk in enumerate(chunks):
        piece = chunk + ("\n" if i < len(chunks) - 1 else "")
        end = ";" if i == len(chunks) - 1 else " +"
        lines.append(f"        {literal(piece)}{end}")
    lines.append("")
lines[-1] = "}"
pathlib.Path("src/MeetingPreps/PromptText.g.cs").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
